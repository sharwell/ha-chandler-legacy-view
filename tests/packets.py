def raw_advertisement(*segments: bytes) -> bytes:
    """Wrap company-prefixed payloads in Bluetooth manufacturer AD structures."""

    return b"\x02\x01\x06" + b"".join(
        bytes((len(segment) + 1, 0xFF)) + segment for segment in segments
    )
